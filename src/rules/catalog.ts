import type { Classification, Confidence, Severity } from '../core/types.js';

export type RuleType = 'unit' | 'api' | 'e2e' | 'parser';

export interface RuleDefinition {
  readonly id: string;
  readonly type: RuleType;
  readonly classification: Classification;
  readonly severity: Severity;
  readonly confidence: Confidence;
  readonly description: {
    readonly en: string;
    readonly zh: string;
  };
  readonly evidenceBoundary: {
    readonly en: string;
    readonly zh: string;
  };
}

function rule(
  id: string,
  type: RuleType,
  classification: Classification,
  severity: Severity,
  description: string,
  descriptionZh: string,
  evidenceBoundary: string,
  evidenceBoundaryZh: string,
): RuleDefinition {
  return {
    id,
    type,
    classification,
    severity,
    confidence: 'HIGH',
    description: { en: description, zh: descriptionZh },
    evidenceBoundary: { en: evidenceBoundary, zh: evidenceBoundaryZh },
  };
}

